"""Modular generator for Cat 3D Viewer (examples/cat-3d.html).

Generates:
1. assets/voxels/cat-voxel-data.js — Cat body/paw/belly & hats voxel data on window.__CAT_VOXEL_DATA__
2. examples/cat-3d.css — Stylesheet copied from src/examples/cat-3d/cat-3d.css
3. examples/cat-3d.html — Lightweight HTML shell referencing cat-3d.css and <script src="..."> modules
"""

import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOXELS_DIR = os.path.join(ROOT, 'assets', 'voxels')
SRC_DIR = os.path.join(ROOT, 'src', 'examples', 'cat-3d')
EXAMPLES_DIR = os.path.join(ROOT, 'examples')


def build_cat_voxel_data_js(out_path=None):
    with open(os.path.join(VOXELS_DIR, 'slices_v5.json'), 'r', encoding='utf-8') as f:
        slices_raw = json.load(f)

    # Corpo modular (fatias 0 e 1 sem as patas) + marquinha anime (*) sob a cauda
    cat_body_slices = [[list(r) for r in s] for s in slices_raw]
    for z in (0, 1):
        for y in range(32):
            for x in range(32):
                cat_body_slices[z][y][x] = '0'

    cat_body_slices[2][8][15] = '4'
    cat_body_slices[2][8][16] = '4'
    cat_body_slices[3][8][14] = '4'
    cat_body_slices[3][8][15] = '4'
    cat_body_slices[3][8][16] = '4'
    cat_body_slices[3][8][17] = '4'
    cat_body_slices[4][8][14] = '4'
    cat_body_slices[4][8][17] = '4'

    cat_body_slices = [[''.join(r) for r in s] for s in cat_body_slices]

    cat_paw_slices = [
        ['1441', '4114', '1441', '1111'],
        ['1111', '1111', '1111', '1111'],
    ]

    with open(os.path.join(VOXELS_DIR, 'cat_belly_slices.json'), 'r', encoding='utf-8') as f:
        belly_slices = json.load(f)

    with open(os.path.join(VOXELS_DIR, 'hats_pack.json'), 'r', encoding='utf-8') as f:
        hats_pack = json.load(f)

    payload = {
        'BODY_SLICES': cat_body_slices,
        'PAW_SLICES': cat_paw_slices,
        'BELLY_SLICES': belly_slices,
        'HATS': {
            'witch': hats_pack['witch'],
            'crown': hats_pack['crown'],
            'beret': hats_pack['beret'],
            'flower': hats_pack['flower'],
        },
    }

    js_out = (
        '// Auto-generated by scripts/generate_html.py\n'
        'window.__CAT_VOXEL_DATA__ = '
        + json.dumps(payload, separators=(',', ':'))
        + ';\n'
    )
    if out_path is None:
        out_path = os.path.join(VOXELS_DIR, 'cat-voxel-data.js')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js_out)
    return out_path


def build_cat_html(out_path=None):
    os.makedirs(EXAMPLES_DIR, exist_ok=True)
    voxel_js_path = build_cat_voxel_data_js()

    css_src = os.path.join(SRC_DIR, 'cat-3d.css')
    css_out = os.path.join(EXAMPLES_DIR, 'cat-3d.css')
    with open(css_src, 'r', encoding='utf-8') as f:
        css_text = f.read()
    with open(css_out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css_text)

    shell_path = os.path.join(SRC_DIR, 'shell.html')
    with open(shell_path, 'r', encoding='utf-8') as f:
        shell_html = f.read()

    module_paths = sorted(glob.glob(os.path.join(SRC_DIR, '*.js')))
    if not module_paths:
        raise RuntimeError(f'No JS modules found in {SRC_DIR}')

    all_scripts = [voxel_js_path] + module_paths
    script_tags = []
    for mod_path in all_scripts:
        rel_url = os.path.relpath(mod_path, EXAMPLES_DIR).replace('\\', '/')
        script_tags.append(f'  <script src="{rel_url}"></script>')
    scripts_block = '\n'.join(script_tags)

    html_out = shell_html.replace('__CAT_SCRIPTS__', scripts_block)
    unresolved = re.findall(r'__[A-Z_]+__', html_out)
    if unresolved:
        raise RuntimeError(f'Unresolved template placeholders: {unresolved}')

    if out_path is None:
        out_path = os.path.join(EXAMPLES_DIR, 'cat-3d.html')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html_out)

    print(
        f'SUCCESS: Generated modular Cat 3D ({len(module_paths)} module(s)) -> '
        f'{out_path} ({os.path.getsize(out_path) / 1024:.1f} KB), '
        f'{css_out} ({os.path.getsize(css_out) / 1024:.1f} KB), '
        f'{voxel_js_path} ({os.path.getsize(voxel_js_path) / 1024:.1f} KB)'
    )
    return out_path


if __name__ == '__main__':
    build_cat_html()
