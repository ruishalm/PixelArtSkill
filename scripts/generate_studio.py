"""Zero-dependency modular generator for Voxel 3D Studio (studio/index.html).

Generates:
1. assets/voxels/voxel-data.js — Base-36 / RLE voxel packs on window.__VOXEL_PACKS__
2. studio/studio.css — Studio UI stylesheet copied from src/studio/studio.css
3. studio/index.html — Lightweight HTML shell referencing studio.css and <script src="..."> modules
"""

import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOXELS_DIR = os.path.join(ROOT, 'assets', 'voxels')
ENGINE_DIR = os.path.join(ROOT, 'src', 'engine')
WORLD_DIR = os.path.join(ROOT, 'src', 'terrain-world')
STUDIO_DIR = os.path.join(ROOT, 'src', 'studio')
STUDIO_OUT_DIR = os.path.join(ROOT, 'studio')
_RLE_RE = re.compile(r'(.)\1{2,}')


def rle_compress_props(pack):
    compressed = {}
    for key, entry in pack.items():
        compressed[key] = {
            'palette': entry['palette'],
            'slices': [
                [_RLE_RE.sub(lambda m: f'*{m.group(1)}{len(m.group(0))};', row) for row in sl]
                for sl in entry['slices']
            ],
        }
    return compressed


def build_voxel_data_js(out_path=None):
    with open(os.path.join(VOXELS_DIR, 'slices_v5.json'), 'r', encoding='utf-8') as f:
        cat_slices = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'hats_pack.json'), 'r', encoding='utf-8') as f:
        hats_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'chicken_slices.json'), 'r', encoding='utf-8') as f:
        chicken_data = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'terrain_props_pack.json'), 'r', encoding='utf-8') as f:
        props_pack = json.load(f)

    payload = {
        'CAT_BODY_DATA': cat_slices,
        'HATS_DATA': hats_pack,
        'CHICKEN_DATA': chicken_data,
        'PROPS_DATA': rle_compress_props(props_pack),
    }
    js_out = (
        '// Auto-generated by scripts/generate_studio.py (Base-36 / RLE voxel packs)\n'
        'window.__VOXEL_PACKS__ = '
        + json.dumps(payload, separators=(',', ':'))
        + ';\n'
    )
    if out_path is None:
        out_path = os.path.join(VOXELS_DIR, 'voxel-data.js')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js_out)
    return out_path


def build_studio(out_path=None):
    os.makedirs(STUDIO_OUT_DIR, exist_ok=True)
    voxel_js_path = build_voxel_data_js()

    css_src = os.path.join(STUDIO_DIR, 'studio.css')
    css_out = os.path.join(STUDIO_OUT_DIR, 'studio.css')
    with open(css_src, 'r', encoding='utf-8') as f:
        css_text = f.read()
    with open(css_out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css_text)

    shell_path = os.path.join(STUDIO_DIR, 'shell.html')
    with open(shell_path, 'r', encoding='utf-8') as f:
        shell_html = f.read()

    engine_paths = sorted(glob.glob(os.path.join(ENGINE_DIR, '*.js')))
    world_paths = sorted(glob.glob(os.path.join(WORLD_DIR, '*.js')))
    studio_paths = sorted(glob.glob(os.path.join(STUDIO_DIR, '*.js')))
    if not studio_paths:
        raise RuntimeError(f'No studio JS modules found in {STUDIO_DIR}')

    all_scripts = [voxel_js_path] + engine_paths + world_paths + studio_paths
    script_tags = []
    for mod_path in all_scripts:
        rel_url = os.path.relpath(mod_path, STUDIO_OUT_DIR).replace('\\', '/')
        script_tags.append(f' <script src="{rel_url}"></script>')
    scripts_block = '\n'.join(script_tags)

    html_out = shell_html.replace('__STUDIO_SCRIPTS__', scripts_block)
    unresolved = re.findall(r'__(?:STUDIO_SCRIPTS|STUDIO_JS_BUNDLE|CAT_SLICES|HATS_PACK|CHICKEN_DATA|PROPS_PACK)__', html_out)
    if unresolved:
        raise RuntimeError(f'Unresolved template placeholders: {unresolved}')

    if out_path is None:
        out_path = os.path.join(STUDIO_OUT_DIR, 'index.html')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html_out)

    print(
        f'SUCCESS: Generated modular Studio ({len(engine_paths)} engine + {len(world_paths)} world + {len(studio_paths)} studio) -> '
        f'{out_path} ({os.path.getsize(out_path) / 1024:.1f} KB), '
        f'{css_out} ({os.path.getsize(css_out) / 1024:.1f} KB), '
        f'{voxel_js_path} ({os.path.getsize(voxel_js_path) / 1024:.1f} KB)'
    )
    return out_path


if __name__ == '__main__':
    build_studio()
