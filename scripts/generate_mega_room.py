"""Modular generator for Mega Room 3D Diorama (examples/room-3d.html & index.html).

Generates:
1. assets/voxels/room-voxel-data.js — Room furniture, cat, hats, chicken & chick voxel packs on window.__ROOM_VOXEL_DATA__
2. examples/room-3d.css — Stylesheet copied from src/examples/room-3d/room-3d.css
3. examples/room-3d.html & index.html — Lightweight HTML shells referencing room-3d.css and <script src="..."> modules
"""

import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOXELS_DIR = os.path.join(ROOT, 'assets', 'voxels')
SRC_DIR = os.path.join(ROOT, 'src', 'examples', 'room-3d')
EXAMPLES_DIR = os.path.join(ROOT, 'examples')


def build_room_voxel_data_js(out_path=None):
    with open(os.path.join(VOXELS_DIR, 'slices_v5.json'), 'r', encoding='utf-8') as f:
        cat_slices_raw = json.load(f)

    # Corpo modular (fatias 0 e 1 sem as patas) + marquinha anime (*) sob a cauda
    cat_body_slices = [[list(r) for r in s] for s in cat_slices_raw]
    for z in (0, 1):
        for y in range(32):
            for x in range(32):
                cat_body_slices[z][y][x] = '0'

    cat_body_slices[2][8][15] = '4'
    cat_body_slices[2][8][16] = '4'
    cat_body_slices[3][8][14] = '4'
    cat_body_slices[3][8][15] = '4'
    cat_body_slices[3][8][16] = '4'
    cat_body_slices[3][8][17] = '4'
    cat_body_slices[4][8][14] = '4'
    cat_body_slices[4][8][17] = '4'
    cat_body_slices = [[''.join(r) for r in s] for s in cat_body_slices]

    cat_paw_slices = [
        ['1441', '4114', '1441', '1111'],
        ['1111', '1111', '1111', '1111'],
    ]

    with open(os.path.join(VOXELS_DIR, 'cat_belly_slices.json'), 'r', encoding='utf-8') as f:
        cat_belly_slices = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'hats_pack.json'), 'r', encoding='utf-8') as f:
        hats_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'furniture_pack.json'), 'r', encoding='utf-8') as f:
        furn_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'modular_desk_pack.json'), 'r', encoding='utf-8') as f:
        mod_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'living_room_pack.json'), 'r', encoding='utf-8') as f:
        living_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'kitchen_pack.json'), 'r', encoding='utf-8') as f:
        kitchen_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'garden_pack.json'), 'r', encoding='utf-8') as f:
        garden_pack = json.load(f)
    with open(os.path.join(VOXELS_DIR, 'room_pets_pack.json'), 'r', encoding='utf-8') as f:
        pets_pack = json.load(f)

    payload = {
        'CAT_BODY_SLICES': cat_body_slices,
        'CAT_PAW_SLICES': cat_paw_slices,
        'CAT_BELLY_SLICES': cat_belly_slices,
        'WITCH_HAT_SLICES': hats_pack['witch'],
        'CROWN_HAT_SLICES': hats_pack['crown'],
        'BERET_HAT_SLICES': hats_pack['beret'],
        'FLOWER_HAT_SLICES': hats_pack['flower'],
        'DESK_SLICES': mod_pack['desk'],
        'LAPTOP_SLICES': mod_pack['laptop'],
        'TABLET_SLICES': mod_pack['tablet'],
        'DESK_BOOKS_SLICES': mod_pack['desk_books'],
        'MUG_SLICES': mod_pack['mug'],
        'PLANT_SLICES': furn_pack['plant'],
        'BED_SLICES': furn_pack['bed'],
        'TREE_SLICES': furn_pack['cat_tree'],
        'SOFA_SLICES': living_pack['sofa'],
        'COFFEE_TABLE_SLICES': living_pack['coffee_table'],
        'TV_RACK_SLICES': living_pack['tv_rack'],
        'BOOKSHELF_SLICES': living_pack['bookshelf'],
        'BS_ENC_SLICES': living_pack['bs_encyclopedia'],
        'BS_PLANT_SLICES': living_pack['bs_plant'],
        'BS_CRYSTAL_SLICES': living_pack['bs_crystal'],
        'BS_STACK_SLICES': living_pack['bs_stack'],
        'BS_TROPHY_SLICES': living_pack['bs_trophy'],
        'COUNTER_SLICES': kitchen_pack['kitchen_counter'],
        'FRIDGE_SLICES': kitchen_pack['fridge_retro'],
        'SIDEBOARD_SLICES': kitchen_pack['kitchen_sideboard'],
        'DINING_TABLE_SLICES': kitchen_pack['dining_table'],
        'DINING_CHAIR_SLICES': kitchen_pack['dining_chair'],
        'FRUIT_BOWL_SLICES': kitchen_pack['fruit_bowl'],
        'GARDEN_TREE_SLICES': garden_pack['garden_tree'],
        'TIRE_SWING_SLICES': garden_pack['tire_swing'],
        'PORCH_CHAIR_SLICES': garden_pack['porch_chair'],
        'WHEELBARROW_SLICES': garden_pack['wheelbarrow_flowers'],
        'FLOWER_BED_SLICES': garden_pack['flower_bed'],
        'CHICKEN_SLICES': pets_pack['chicken'],
        'CHICK_SLICES': pets_pack['chick'],
    }

    js_out = (
        '// Auto-generated by scripts/generate_mega_room.py\n'
        'window.__ROOM_VOXEL_DATA__ = '
        + json.dumps(payload, separators=(',', ':'))
        + ';\n'
    )
    if out_path is None:
        out_path = os.path.join(VOXELS_DIR, 'room-voxel-data.js')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js_out)
    return out_path


def _render_html_for_base(shell_html, css_out, all_scripts, base_dir):
    css_rel = os.path.relpath(css_out, base_dir).replace('\\', '/')
    script_tags = []
    for mod_path in all_scripts:
        rel_url = os.path.relpath(mod_path, base_dir).replace('\\', '/')
        script_tags.append(f'  <script src="{rel_url}"></script>')
    scripts_block = '\n'.join(script_tags)

    html_out = shell_html.replace('__ROOM_CSS__', css_rel).replace('__ROOM_SCRIPTS__', scripts_block)
    unresolved = re.findall(r'__[A-Z_]+__', html_out)
    if unresolved:
        raise RuntimeError(f'Unresolved template placeholders: {unresolved}')
    return html_out


def build_mega_room(out_room_path=None, out_index_path=None):
    os.makedirs(EXAMPLES_DIR, exist_ok=True)
    voxel_js_path = build_room_voxel_data_js()

    css_src = os.path.join(SRC_DIR, 'room-3d.css')
    css_out = os.path.join(EXAMPLES_DIR, 'room-3d.css')
    with open(css_src, 'r', encoding='utf-8') as f:
        css_text = f.read()
    with open(css_out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css_text)

    shell_path = os.path.join(SRC_DIR, 'shell.html')
    with open(shell_path, 'r', encoding='utf-8') as f:
        shell_html = f.read()

    module_paths = sorted(glob.glob(os.path.join(SRC_DIR, '*.js')))
    if not module_paths:
        raise RuntimeError(f'No JS modules found in {SRC_DIR}')

    all_scripts = [voxel_js_path] + module_paths

    if out_room_path is None:
        out_room_path = os.path.join(EXAMPLES_DIR, 'room-3d.html')
    if out_index_path is None:
        out_index_path = os.path.join(ROOT, 'index.html')

    room_html = _render_html_for_base(shell_html, css_out, all_scripts, EXAMPLES_DIR)
    index_html = _render_html_for_base(shell_html, css_out, all_scripts, ROOT)

    with open(out_room_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(room_html)
    with open(out_index_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(index_html)

    print(
        f'SUCCESS: Generated modular Room 3D ({len(module_paths)} modules) -> '
        f'{out_room_path} ({os.path.getsize(out_room_path) / 1024:.1f} KB), '
        f'{out_index_path} ({os.path.getsize(out_index_path) / 1024:.1f} KB), '
        f'{css_out} ({os.path.getsize(css_out) / 1024:.1f} KB), '
        f'{voxel_js_path} ({os.path.getsize(voxel_js_path) / 1024:.1f} KB)'
    )
    return out_room_path, out_index_path


if __name__ == '__main__':
    build_mega_room()
