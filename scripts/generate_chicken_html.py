"""Modular generator for Chicken 3D Viewer (examples/chicken-3d.html).

Generates:
1. assets/voxels/chicken-voxel-data.js — Chicken slices on window.__CHICKEN_VOXEL_DATA__
2. examples/chicken-3d.css — Stylesheet copied from src/examples/chicken-3d/chicken-3d.css
3. examples/chicken-3d.html — Lightweight HTML shell referencing chicken-3d.css and <script src="..."> modules
"""

import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOXELS_DIR = os.path.join(ROOT, 'assets', 'voxels')
SRC_DIR = os.path.join(ROOT, 'src', 'examples', 'chicken-3d')
EXAMPLES_DIR = os.path.join(ROOT, 'examples')


def build_chicken_voxel_data_js(out_path=None):
    with open(os.path.join(VOXELS_DIR, 'chicken_slices.json'), 'r', encoding='utf-8') as f:
        chicken_data = json.load(f)

    js_out = (
        '// Auto-generated by scripts/generate_chicken_html.py\n'
        'window.__CHICKEN_VOXEL_DATA__ = '
        + json.dumps(chicken_data, separators=(',', ':'))
        + ';\n'
    )
    if out_path is None:
        out_path = os.path.join(VOXELS_DIR, 'chicken-voxel-data.js')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js_out)
    return out_path


def build_chicken_html(out_path=None):
    os.makedirs(EXAMPLES_DIR, exist_ok=True)
    voxel_js_path = build_chicken_voxel_data_js()

    css_src = os.path.join(SRC_DIR, 'chicken-3d.css')
    css_out = os.path.join(EXAMPLES_DIR, 'chicken-3d.css')
    with open(css_src, 'r', encoding='utf-8') as f:
        css_text = f.read()
    with open(css_out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css_text)

    shell_path = os.path.join(SRC_DIR, 'shell.html')
    with open(shell_path, 'r', encoding='utf-8') as f:
        shell_html = f.read()

    module_paths = sorted(glob.glob(os.path.join(SRC_DIR, '*.js')))
    if not module_paths:
        raise RuntimeError(f'No JS modules found in {SRC_DIR}')

    all_scripts = [voxel_js_path] + module_paths
    script_tags = []
    for mod_path in all_scripts:
        rel_url = os.path.relpath(mod_path, EXAMPLES_DIR).replace('\\', '/')
        script_tags.append(f'  <script src="{rel_url}"></script>')
    scripts_block = '\n'.join(script_tags)

    html_out = shell_html.replace('__CHICKEN_SCRIPTS__', scripts_block)
    unresolved = re.findall(r'__[A-Z_]+__', html_out)
    if unresolved:
        raise RuntimeError(f'Unresolved template placeholders: {unresolved}')

    if out_path is None:
        out_path = os.path.join(EXAMPLES_DIR, 'chicken-3d.html')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html_out)

    print(
        f'SUCCESS: Generated modular Chicken 3D ({len(module_paths)} module(s)) -> '
        f'{out_path} ({os.path.getsize(out_path) / 1024:.1f} KB), '
        f'{css_out} ({os.path.getsize(css_out) / 1024:.1f} KB), '
        f'{voxel_js_path} ({os.path.getsize(voxel_js_path) / 1024:.1f} KB)'
    )
    return out_path


if __name__ == '__main__':
    build_chicken_html()
